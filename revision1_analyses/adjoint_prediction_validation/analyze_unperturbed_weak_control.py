#!/usr/bin/env python3
"""Predict ng=0 responses with the mean sensitivity of each sg ensemble.

Separate from analyze_with_weak_control.py (which evaluates ng=sg).
Reuses the cache generated by validate_adjoint_prediction.py; never runs WRF
or modifies input files.

by Shan Jiang, FDL, Nagoya University
"""
from __future__ import annotations
import argparse
import hashlib
import json
import multiprocessing
from concurrent.futures import ProcessPoolExecutor
from datetime import datetime, timezone
from pathlib import Path
import validate_adjoint_prediction as base
from analyze_with_weak_control import check_file, HERE, ULTRAWEAK, WEAK

KEYS = ('s_raw', 'j_baseline_mm', 'delta_actual', 'j_controlled_mm', 'new_zero_grid_fraction')


def nl_path(root, sg, ca):
    return root/f'absG_i0M_NOV0.02_ng0_ig{ca}_sg{sg}'/'wrfout_d01_2018-07-05_120000_woinput_NL1'


def read_control(path):
    check_file(str(path))
    return base.read_nl_member(Path(path), 6, 34, 16)


def assemble(old, q0, j0, controls, nact):
    """One actual trajectory per (sg,Cact); gradient is mean over AD members."""
    np = base.np
    nsg = len(base.DEFAULT_CPERT)
    q = np.stack([x['q_controlled'] for x in controls]).reshape(nsg, nact, *q0.shape)
    delta = q - q0
    gradients = np.mean(old['s_raw'], axis=1, dtype=np.float64)
    gradients[0] = old['s_raw'][0, 0]  # pure deterministic gradient
    tol = 1e-12
    newly_zero = (q <= tol) & (q0 > tol) & (delta < -tol)
    arrays = {
        's_raw': gradients[:, None],
        'j_baseline_mm': np.full((nsg, 1), j0),
        'delta_actual': delta[:, :, None],
        'j_controlled_mm': np.asarray([x['j_controlled'] for x in controls]).reshape(nsg,nact,1),
        'new_zero_grid_fraction': np.mean(newly_zero, axis=(-2,-1))[:, :, None],
    }
    for name, array in arrays.items():
        if not np.isfinite(array).all():
            raise ValueError(f'Nonfinite values in {name}')
    return arrays


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--weak-root', type=Path, default=HERE/'weak_control_experiments/outputdir')
    # --old-nl-root selects standard-actuation outputs (dataset-root wrfout/NL/).
    p.add_argument('--old-nl-root', type=Path, default=base.DEFAULT_NL_ROOT)
    p.add_argument('--run-name', default='unperturbed_with_weak_control')
    p.add_argument('--overwrite', action='store_true', help='Allow existing outputs in the selected result directory to be replaced.')
    p.add_argument('--workers', type=int, default=4)
    modes = p.add_mutually_exclusive_group()
    modes.add_argument('--from-cache', action='store_true')
    modes.add_argument('--check-only', action='store_true')
    p.add_argument('--weak-only', action='store_true', help='Only 8 weak Cact values; default includes all 17.')
    p.add_argument('--no-plots', action='store_true')
    opt = p.parse_args()
    if opt.workers < 1:
        p.error('--workers must be positive')
    if Path(opt.run_name).name != opt.run_name or opt.run_name in ('', '.', '..'):
        p.error('--run-name must be a single directory name')
    opt.weak_root = opt.weak_root.expanduser().resolve()
    opt.old_nl_root = opt.old_nl_root.expanduser().resolve()
    args = base.parse_args([])
    args.workers = opt.workers
    args.from_cache = opt.from_cache
    args.overwrite = opt.overwrite
    old_cache = base.matching_cache_directory(args)
    cact = sorted(WEAK if opt.weak_only else list(base.DEFAULT_CACT)+WEAK, key=float)
    paths = [nl_path(opt.weak_root if ca in WEAK else opt.old_nl_root, sg, ca)
             for sg in base.DEFAULT_CPERT for ca in cact]
    signature = {
        'schema': 1, 'validation': 'ng0', 'old_sensitivity_cache': str(old_cache),
        'weak_root': str(opt.weak_root), 'old_nl_root': str(opt.old_nl_root),
        'cact': cact, 'baseline': str(base.ad_file(args.ad_root, '0', 1)),
        'target': [34,16], 'rain_time': 6, 'adjoint_time': -1, 'zero_tolerance': 1e-12,
    }
    digest = hashlib.sha256(json.dumps(signature,sort_keys=True).encode()).hexdigest()[:16]
    cache_dir = HERE/'cache_unperturbed'/f'cache_{digest}'
    out = HERE/'results'/opt.run_name
    for dest in (cache_dir, out):
        base.ensure_output_is_separate(dest, (args.ad_root, opt.weak_root, opt.old_nl_root))
    if not opt.check_only and out.exists() and not opt.overwrite:
        p.error(f'Result directory exists: {out}; pass --overwrite to replace its outputs')
    if opt.check_only:
        missing = [str(path) for path in paths if not path.is_file()]
        if missing:
            raise FileNotFoundError(f'Missing {len(missing)} ng0 files; first 10:\n'+'\n'.join(missing[:10]))
        with ProcessPoolExecutor(max_workers=opt.workers, mp_context=multiprocessing.get_context('spawn')) as pool:
            for _ in pool.map(check_file, map(str, paths)):
                pass
        print(f'Checked {len(paths)} ng0 outputs, variables and hourly timestamps; wrote nothing.')
        return
    base.load_scientific_dependencies()
    if cache_dir.exists():
        metadata = json.loads((cache_dir/'metadata.json').read_text())
        if metadata.get('signature') != signature or metadata.get('complete') is not True:
            raise ValueError(f'Incomplete/mismatched cache: {cache_dir}')
        arrays = {key: base.np.load(cache_dir/f'{key}.npy', mmap_mode='r', allow_pickle=False) for key in KEYS}
        print(f'Using ng0 cache: {cache_dir}', flush=True)
    else:
        if opt.from_cache:
            raise FileNotFoundError(f'No matching ng0 cache: {cache_dir}; run once without --from-cache')
        missing = [str(path) for path in paths if not path.is_file()]
        if missing:
            raise FileNotFoundError(f'Missing {len(missing)} ng0 files; first 10:\n'+'\n'.join(missing[:10]))
        old, old_cache, _ = base.obtain_cache(args)
        baseline = base.read_ad_member(base.ad_file(args.ad_root,'0',1),6,-1,34,16)
        if not base.np.isclose(baseline['j_baseline'], old['j_baseline_mm'][0,0], rtol=0, atol=1e-8):
            raise ValueError('Unperturbed baseline objective differs from prediction-validation cache')
        print(f'Reading {len(paths)} ng0 responses with {opt.workers} workers...',flush=True)
        with ProcessPoolExecutor(max_workers=opt.workers, mp_context=multiprocessing.get_context('spawn')) as pool:
            controls=[]
            for i, data in enumerate(pool.map(read_control, map(str,paths)),1):
                controls.append(data)
                if i%10==0: print(f'Read {i}/{len(paths)}',flush=True)
        arrays = assemble(old, baseline['q_baseline'], baseline['j_baseline'], controls, len(cact))
        cache_dir.mkdir(parents=True,exist_ok=False)
        for key, array in arrays.items():
            base.write_npy_exclusive(cache_dir/f'{key}.npy',array)
        (cache_dir/'metadata.json').write_text(json.dumps({'complete':True,'signature':signature},indent=2)+'\n')
    args.members=1
    args.cact=cact
    members, rows, deterministic = base.analyze_from_cache(args, arrays)
    for row in members+rows:
        pred,true = row['delta_j_pred_mm'],row['delta_j_true_mm']
        if not base.np.isfinite(pred) or not base.np.isfinite(true):
            raise ValueError('Nonfinite prediction/response')
        row['validation_ng']=0
        row['sensitivity_members']=1 if row['cpert_label']=='0' else 100
        row['pred_over_true']=pred/true if true!=0 else float('nan')
        row['truth_relative_error_without_floor']=abs(pred-true)/abs(true) if true!=0 else float('nan')
    if len(rows)!=10*len(cact): raise ValueError('Incorrect comparison count')
    out.mkdir(parents=True,exist_ok=opt.overwrite)
    base.write_csv(out/'unperturbed_summary.csv',rows,overwrite=opt.overwrite)
    base.write_csv(out/'deterministic_summary.csv',deterministic,overwrite=opt.overwrite)
    metric_groups = [
        ('ng0_all', rows),
        ('ng0_weak', [r for r in rows if r['cact_label'] in WEAK]),
        ('ng0_ultraweak', [r for r in rows if r['cact_label'] in ULTRAWEAK]),
    ]
    base.write_csv(
        out/'global_metrics.csv',
        [{'analysis': label, **base.linear_fit_metrics(group)} for label, group in metric_groups],
        overwrite=opt.overwrite,
    )
    base.save_npz(out/'adjoint_prediction_validation.npz',rows,args.cpert,cact,overwrite=opt.overwrite)
    meta={'created_utc':datetime.now(timezone.utc).isoformat(),'signature':signature,
          'cache':str(cache_dir),'cpert':args.cpert,'cact':cact,
          'prediction':'(-1/60) * mean_k(A_QVAPOR_k) dot (q_controlled_initial - q_unperturbed_initial)',
          'truth':'J_controlled - J_unperturbed; J is the normalized 3x3 weighted RAINNC',
          'raw_to_objective_scale':args.raw_to_objective_scale,'error_floor_mm':args.error_floor_mm,
          'overwrite_existing_results':opt.overwrite,
          'validation_members_per_case':1,'sensitivity_members_nonzero_cpert':100,
          'note':'One validation trajectory, not a 100-member response mean. Zero member std is not uncertainty. No ng=sg deltaP reference is used.'}
    metadata_mode = 'w' if opt.overwrite else 'x'
    with (out/'metadata.json').open(metadata_mode, encoding='utf-8') as handle:
        handle.write(json.dumps(meta,indent=2)+'\n')
    if not opt.no_plots:
        base.plot_prediction_scatter(rows,deterministic,cact,out,overwrite=opt.overwrite)
        base.plot_error_vs_cpert(rows,args.cpert,cact,out,overwrite=opt.overwrite)
        base.plot_error_vs_cact(rows,args.cpert,cact,out,overwrite=opt.overwrite)
        base.plot_deterministic(deterministic,out,overwrite=opt.overwrite)
    print(f'Completed {len(rows)} ng0 comparisons: {out}')


if __name__=='__main__':
    main()
